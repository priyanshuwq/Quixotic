    fun isRomanScript(text: String): Boolean {
        return text.all { it.isLetter() && it.code < 0x0900 }
    }

    fun convert(input: String): String {
        val words = input.split("\\s+".toRegex())
        val converted = words.map { word ->
            val clean = word.lowercase()
                .replace(Regex("[,\\.?!;:...]"), "")
            romanToHindi[clean] ?: word
        }
        return converted.joinToString(" ")
    }
